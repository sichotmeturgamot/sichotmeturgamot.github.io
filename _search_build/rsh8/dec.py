import re
M={'`':'א','a':'ב','b':'ג','c':'ד','d':'ה','e':'ו','f':'ז','g':'ח','h':'ט','i':'י','j':'ך','k':'כ','l':'ל','m':'ם','n':'מ','o':'ן','p':'נ','q':'ס','r':'ע','s':'ף','t':'פ','u':'ץ','v':'צ','w':'ק','x':'ר','y':'ש','z':'ת',
   'Î':'־','Ð':'—','Z':'„','(':')',')':'(','[':']',']':'['}
def dec(line):
    s=''.join(M.get(ch,ch) for ch in line)[::-1]
    return re.sub(r'\d+', lambda m: m.group(0)[::-1], s)
