LAST = 344
def chap(pg): return max(i for i, c in enumerate(CH) if c[0] <= pg)
def sim(a, b): return difflib.SequenceMatcher(None, re.sub(r'\W', '', a), re.sub(r'\W', '', b)).ratio()
def fixline(s):
    s = s.translate(str.maketrans('()', ')('))
    s = re.sub(r'\s+([.,:;!?])(?=\S)', r'\1 ', s)
    s = re.sub(r'\s+([.,:;!?])\s*$', r'\1', s)
    s = re.sub(r'\s+-\s*|\s*-\s+', ' — ', s)
    return re.sub(r'\s{2,}', ' ', s).strip()
os.makedirs('pages', exist_ok=True)
pagechap = {}
for pg in range(7, LAST + 1):
    ci = chap(pg); title = CH[ci][2]; pagechap[pg] = ci
    L = [l.strip() for l in P[pg - 1].split('\n') if l.strip()]
    out = []
    for k, s in enumerate(L):
        if s.startswith('*'): break                       # הערות שוליים בתחתית
        if k < 4:
            if re.fullmatch(r'[\d I\.י]{1,8}', s) or re.match(r'^ספר הז.{0,3}רו.{0,2}ת$', s): continue
            if len(s.split()) <= 9 and sim(s, title) > 0.6: continue
            if CH[ci][0] == pg and re.match(r'^פרק', s): continue
            if pg >= 342 and s == 'הוספות והערות': continue
        out.append(fixline(s))
    open('pages/%03d.txt' % pg, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
json.dump({'CH': CH, 'OFF': OFF, 'LAST': LAST}, open('struct.json', 'w'), ensure_ascii=False)
